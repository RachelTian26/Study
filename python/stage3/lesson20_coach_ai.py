# ---------- 3.5 AI 坏掉的时候，工具不能跟着坏 ----------
"""
    第 3 阶段的验收标准里有这么一条：

        断网时程序给出一句人话提示，不是一屏红色报错

    今天把它做到。策略叫**优雅降级**（graceful degradation）：
    AI 用不了的时候，退回到一个虽然笨但能用的版本。

        AI 能用   → AI 出题（好题）、AI 判卷（能判近义词）
        AI 挂了   → 直接把知识点当题目问"还记得吗 (y/n)"、字符串比对判分

    第 19 课第 6 题你写的那个"假装出题"的占位实现，
    今天不要删 —— **它就是你的降级方案。**

    ★ 这是个很实用的设计思维：
      "先写个笨的能跑的版本，再加聪明的" ——
      笨版本不只是过渡，它天然就是聪明版本的兜底。
"""


def make_question_safe(topic, ai_available=True):
    """出一道题。AI 不可用或出错时，自动退回笨办法。"""
    if ai_available and HAS_KEY:
        raw = chat([
            {"role": "system", "content": PROMPT_B},
            {"role": "user", "content": wrap_untrusted(topic)},
        ], temperature=0.8)
        data = parse_json(raw)
        if valid_question(data):
            return data, "ai"
        print("  （AI 出题失败，用备用方案）")
    # 降级方案：把知识点本身当题目
    return {"q": f"还记得这个吗：{topic}", "a": "记得"}, "fallback"


