def chat(messages, timeout=90, **options):
    """第 18 课 3.2 那个函数，原样搬过来。"""
    import requests
    try:
        resp = requests.post(
            f"{env['AI_API_BASE']}/chat/completions",
            headers={
                "Authorization": f"Bearer {env['AI_API_KEY']}",
                "Content-Type": "application/json",
            },
            json={"model": env["AI_MODEL"], "messages": messages, **options},
            timeout=timeout,
        )
        resp.raise_for_status()
        return resp.json()["choices"][0]["message"]["content"]
    except requests.Timeout:
        print(f"⏰ 超时（{timeout} 秒）")
    except requests.ConnectionError:
        print("🔌 连不上，检查网络")
    except requests.HTTPError as e:
        print(f"❌ HTTP {e.response.status_code}：{e.response.text[:100]}")
    except (ValueError, KeyError):
        print("📄 返回的东西看不懂")
    return None


# ---------- 3.1 解析模型返回的 JSON：三层防线 ----------

def parse_json(text):
    """把模型返回的文本变成字典。任何一步失败都返回 None，不抛异常。"""
    if not text:
        return None
    text = text.strip()

    # 第一层：剥掉 markdown 代码块
    #   模型很爱写 ```json ... ```，即使你叫它别写
    if text.startswith("```"):
        lines = text.split("\n")
        text = "\n".join(lines[1:-1]) if len(lines) > 2 else text
        text = text.strip()

    # 第二层：解析
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        print(f"⚠ 不是合法 JSON，它返回的是：{text[:80]}")
        return None

    # 第三层：类型要对
    #   模型有时候会返回一个列表而不是字典，虽然你明明要的是字典
    if not isinstance(data, dict):
        print(f"⚠ 期望字典，拿到的是 {type(data).__name__}")
        return None

    return data


# 三层各自能挡住什么，我们直接演示（不需要联网）：
print(parse_json('{"q": "题目", "a": "答案"}'))
# 输出：{'q': '题目', 'a': '答案'}

print(parse_json('```json\n{"q": "题目", "a": "答案"}\n```'))
# 输出：{'q': '题目', 'a': '答案'}        ← 第一层剥掉了代码块

