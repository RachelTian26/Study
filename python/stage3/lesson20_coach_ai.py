# ---------- 3.2 校验字段：解析成功 ≠ 能用 ----------

def valid_question(data):
    """检查这是不是一道能用的题。"""
    if not isinstance(data, dict):
        return False
    if "q" not in data or "a" not in data:
        return False
    # 模型偶尔会返回数字、null、空字符串
    if not isinstance(data["q"], str) or not isinstance(data["a"], str):
        return False
    return bool(data["q"].strip() and data["a"].strip())


print("\n--- 字段校验 ---")
print(valid_question({"q": "题目", "a": "答案"}))
# 输出：True

print(valid_question({"question": "题目", "answer": "答案"}))
# 输出：False        ← 字段名不对。模型很爱自作主张改字段名

print(valid_question({"q": "题目", "a": ""}))
# 输出：False        ← 有字段但是空的

print(valid_question({"q": "题目", "a": 42}))
# 输出：False        ← 类型不对，模型返回了数字
